// PKCS11 service errors.
var (
	ErrPKCS11ServiceNotInitialized = errors.New("pkcs11_service: manager not initialized")
	ErrPKCS11ModuleRequired        = errors.New("pkcs11_service: module path is required")
	ErrPKCS11LabelRequired         = errors.New("pkcs11_service: token label is required")
	ErrPKCS11SOPINRequired         = errors.New("pkcs11_service: security officer PIN is required")
	ErrPKCS11UserPINRequired       = errors.New("pkcs11_service: user PIN is required")
	ErrPKCS11NoSlotsAvailable      = errors.New("pkcs11_service: no slots available in module")
	ErrPKCS11SlotNotFound          = errors.New("pkcs11_service: specified slot not found")
	ErrPKCS11ConfigPersistFailed   = errors.New("pkcs11_service: failed to persist config")
)

// softhsm2ConfigTemplate is the default SoftHSM2 configuration.
const softhsm2ConfigTemplate = `# SoftHSM2 configuration - auto-generated by xkey
directories.tokendir = %s
objectstore.backend = file
log.level = INFO
slots.removable = false
`

