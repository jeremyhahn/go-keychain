// Connect connects to a token and returns the backend.
// The backend can be used for cryptographic operations.
func (s *PKCS11Service) Connect(moduleID string, slotID uint, userPin, soPin string) error {
	if s.manager == nil {
		return ErrPKCS11ServiceNotInitialized
	}
	if userPin == "" {
		return ErrPKCS11UserPINRequired
	}

	s.log.Info("connecting to PKCS#11 token",
		"module_id", moduleID,
		"slot_id", slotID)

	// Get module info to validate slot
	mod, err := s.manager.GetModule(moduleID)
	if err != nil {
		s.log.Error("failed to get module info", "module_id", moduleID, "error", err)
		return fmt.Errorf("module not found: %w", err)
	}

	if len(mod.Slots) == 0 {
		s.log.Error("no slots available in module", "module_id", moduleID)
		return ErrPKCS11NoSlotsAvailable
	}

	// Log available slots for debugging
	s.log.Debug("module slots",
		"module_id", moduleID,
		"slot_count", len(mod.Slots))
	for _, slot := range mod.Slots {
		s.log.Debug("slot info",
			"slot_id", slot.SlotID,
			"label", slot.Label,
			"token_present", slot.TokenPresent,
			"initialized", slot.Initialized)
	}

	// Check if slot exists and is initialized
	slotFound := false
	var tokenLabel string
	for _, slot := range mod.Slots {
		if slot.SlotID == slotID {
			slotFound = true
			tokenLabel = slot.Label
			if !slot.TokenPresent {
				return fmt.Errorf("no token present in slot %d", slotID)
			}
			if !slot.Initialized {
				return fmt.Errorf("token in slot %d is not initialized", slotID)
			}
			break
		}
	}
	if !slotFound {
		// Try to find any available slot
		availableSlots := make([]uint, 0)
		for _, slot := range mod.Slots {
			if slot.TokenPresent && slot.Initialized {
				availableSlots = append(availableSlots, slot.SlotID)
			}
		}
		if len(availableSlots) > 0 {
			return fmt.Errorf("%w: slot %d not found, available initialized slots: %v", ErrPKCS11SlotNotFound, slotID, availableSlots)
		}
		return fmt.Errorf("%w: slot %d (module has %d slots, none initialized)", ErrPKCS11SlotNotFound, slotID, len(mod.Slots))
	}

	_, err = s.manager.Connect(moduleID, slotID, userPin, soPin)
	if err != nil {
		s.log.Error("failed to connect to PKCS#11 token",
			"module_id", moduleID,
			"slot_id", slotID,
			"error", err)
		return fmt.Errorf("connection failed: %w", err)
	}

	s.log.Info("PKCS#11 token connected successfully",
		"module_id", moduleID,
		"slot_id", slotID)

	// Update backend registry state to reflect the live PKCS#11 session.
	// Store connection parameters in metadata so PIV cert storage can be
	// created from registry metadata for on-device certificate storage.
	if s.registry != nil {
		if rb, getErr := s.registry.Get(moduleID); getErr == nil {
			rb.SetState(backendregistry.StateReady)
			if rb.Metadata == nil {
				rb.Metadata = make(map[string]string)
			}
			rb.Metadata["connected_slot"] = fmt.Sprintf("%d", slotID)
			rb.Metadata["library_path"] = mod.LibraryPath
			if tokenLabel != "" {
				rb.Metadata["token_label"] = tokenLabel
			}
		}
	}

	// Notify hook so the PKCS#11 token can be registered as an xkms backend
	// for PIV key generation and other key operations.
	if s.connectHook != nil {
		s.connectHook(moduleID, mod.LibraryPath, slotID, userPin, soPin, tokenLabel)
	}

	return nil
}

// Disconnect closes the PKCS#11 session and logs out from the token.
func (s *PKCS11Service) Disconnect(moduleID string, slotID uint) error {
	if s.manager == nil {
		return ErrPKCS11ServiceNotInitialized
	}
	if err := s.manager.Disconnect(moduleID, slotID); err != nil {
		return err
	}

	s.log.Info("PKCS#11 token disconnected",
		"module_id", moduleID,
		"slot_id", slotID)

	// Update backend registry state to reflect the closed session.
	if s.registry != nil {
		if rb, getErr := s.registry.Get(moduleID); getErr == nil {
			rb.SetState(backendregistry.StateOffline)
		}
	}

	// Notify hook so callers can clean up resources (e.g., FIDO2 key backends).
	if s.disconnectHook != nil {
		s.disconnectHook(moduleID, slotID)
	}

	return nil
}

// GetConnection returns information about an active connection.
func (s *PKCS11Service) GetConnection(moduleID string, slotID uint) (*PKCS11ConnectionInfo, error) {
	if s.manager == nil {
		return nil, ErrPKCS11ServiceNotInitialized
	}
	conn, err := s.manager.GetConnection(moduleID, slotID)
	if err != nil {
		return nil, err
	}
	return &PKCS11ConnectionInfo{
		ModuleID:   conn.ModuleID,
		SlotID:     conn.SlotID,
		TokenLabel: conn.TokenLabel,
	}, nil
}

// ListConnections returns all active connections.
func (s *PKCS11Service) ListConnections() []PKCS11ConnectionInfo {
	if s.manager == nil {
		return nil
	}
	connections := s.manager.ListConnections()
	result := make([]PKCS11ConnectionInfo, len(connections))
	for i, c := range connections {
		result[i] = PKCS11ConnectionInfo{
			ModuleID:   c.ModuleID,
			SlotID:     c.SlotID,
			TokenLabel: c.TokenLabel,
		}
	}
	return result
}

// convertModule converts a manager.ModuleInfo to PKCS11ModuleInfo.
func convertModule(m *manager.ModuleInfo) *PKCS11ModuleInfo {
	return &PKCS11ModuleInfo{
		ID:          m.ID,
		DisplayName: m.DisplayName,
		LibraryPath: m.LibraryPath,
		State:       m.State.String(),
		Slots:       convertSlots(m.Slots),
		ErrorMsg:    m.ErrorMsg,
	}
}

// convertSlots converts a slice of manager.SlotInfo to PKCS11SlotInfo.
func convertSlots(slots []manager.SlotInfo) []PKCS11SlotInfo {
	result := make([]PKCS11SlotInfo, len(slots))
	for i, slot := range slots {
		result[i] = PKCS11SlotInfo{
			SlotID:          slot.SlotID,
			Label:           slot.Label,
			Serial:          slot.Serial,
			Manufacturer:    slot.Manufacturer,
			Model:           slot.Model,
			TokenPresent:    slot.TokenPresent,
			Initialized:     slot.Initialized,
			HardwareVersion: slot.HardwareVersion,
			FirmwareVersion: slot.FirmwareVersion,
		}
	}
	return result
}

// TestConnection tests connectivity to a PKCS#11 module by attempting to
// register, connect to the specified slot, and then clean up. This allows
// validating configuration before permanently adding the backend.
func (s *PKCS11Service) TestConnection(libraryPath string, slotID uint, userPIN string) error {
	if s.manager == nil {
		return ErrPKCS11ServiceNotInitialized
	}
	if libraryPath == "" {
		return ErrPKCS11ModuleRequired
	}
	if userPIN == "" {
		return ErrPKCS11UserPINRequired
	}

	s.log.Info("testing PKCS#11 connection",
		"library", libraryPath,
		"slot_id", slotID)

	// Auto-configure SoftHSM2 if needed
	if isSoftHSM2Module(libraryPath) {
		if err := s.ensureSoftHSM2Config(); err != nil {
			s.log.Error("failed to configure SoftHSM2", "error", err)
			return fmt.Errorf("SoftHSM2 configuration failed: %w", err)
		}
	}

	// Register the module temporarily
	moduleID, err := s.manager.RegisterModule(libraryPath, "test-connection")
	if err != nil {
		s.log.Error("test connection: failed to register module", "error", err)
		return fmt.Errorf("failed to register module: %w", err)
	}

	// Get module info to show available slots
	mod, modErr := s.manager.GetModule(moduleID)
	if modErr == nil {
		s.log.Debug("test connection: module info",
			"slots", len(mod.Slots))
		for _, slot := range mod.Slots {
			s.log.Debug("test connection: slot",
				"slot_id", slot.SlotID,
				"label", slot.Label,
				"token_present", slot.TokenPresent,
				"initialized", slot.Initialized)
		}
	}

	// Try to login to the specified slot (lightweight test, no full backend)
	loginErr := s.manager.TestLogin(moduleID, slotID, userPIN)
	if loginErr != nil {
		s.log.Error("test connection: login failed",
			"slot_id", slotID,
			"error", loginErr)
	} else {
		s.log.Info("test connection: success",
			"slot_id", slotID)
	}

	if loginErr != nil {
		// Cleanup: unregister the module on failure so the next attempt
		// starts fresh (e.g., after the user corrects the PIN).
		_ = s.manager.UnregisterModule(moduleID)
		return fmt.Errorf("connection test failed: %w", loginErr)
	}

	// Retain the registration so a subsequent RegisterModule call for the
	// same library can reuse it without paying the C_Initialize cost again.
	if s.testedModules == nil {
		s.testedModules = make(map[string]string)
	}
	s.testedModulesMu.Lock()
	s.testedModules[libraryPath] = moduleID
	s.testedModulesMu.Unlock()

	return nil
}

// ProbeSlots temporarily registers a PKCS#11 module to enumerate its available
// slots, then immediately unregisters it. This allows the UI to show available
// slots before the user commits to adding the backend.
func (s *PKCS11Service) ProbeSlots(libraryPath string) ([]PKCS11SlotInfo, error) {
	if s.manager == nil {
		return nil, ErrPKCS11ServiceNotInitialized
	}
	if libraryPath == "" {
		return nil, ErrPKCS11ModuleRequired
	}

	s.log.Info("probing PKCS#11 module slots",
		"library", libraryPath)

	// Auto-configure SoftHSM2 if needed
	if isSoftHSM2Module(libraryPath) {
		if err := s.ensureSoftHSM2Config(); err != nil {
			s.log.Error("failed to configure SoftHSM2", "error", err)
			return nil, fmt.Errorf("SoftHSM2 configuration failed: %w", err)
		}
	}

	// Register the module temporarily
	moduleID, err := s.manager.RegisterModule(libraryPath, "probe-slots")
	if err != nil {
		s.log.Error("probe slots: failed to register module", "error", err)
		return nil, fmt.Errorf("failed to probe module: %w", err)
	}

	// Get module info to retrieve slots
	mod, err := s.manager.GetModule(moduleID)
	if err != nil {
		_ = s.manager.UnregisterModule(moduleID)
		return nil, fmt.Errorf("failed to get module info: %w", err)
	}

	// Convert slots
	slots := convertSlots(mod.Slots)

	s.log.Info("probe slots: found slots",
		"count", len(slots))
	for _, slot := range slots {
		s.log.Debug("probe slots: slot info",
			"slot_id", slot.SlotID,
			"label", slot.Label,
			"initialized", slot.Initialized)
	}

	// Unregister the module
	_ = s.manager.UnregisterModule(moduleID)

	return slots, nil
}

// SlotOccupancyInfo describes a single PIV slot's state for the frontend.
type SlotOccupancyInfo struct {
	Slot         string `json:"slot"`
	Name         string `json:"name"`
	Description  string `json:"description"`
	Occupied     bool   `json:"occupied"`
	KeyAlgorithm string `json:"key_algorithm,omitempty"`
	HasCert      bool   `json:"has_cert"`
}

// slotModelProvider is the interface for backends that expose PIV slot models.
// The manager.Backend interface does not include SlotModel(), but the concrete
// pkcs11.Backend type does. This local interface allows a clean type assertion
// without importing the concrete backend package.
type slotModelProvider interface {
	SlotModel() pivcert.SlotModel
}

// GetSlotOccupancy returns PIV slot occupancy for the connected PKCS#11 token.
// Returns nil with no error if the token does not use predefined slots (generic PKCS#11).
func (s *PKCS11Service) GetSlotOccupancy(moduleID string, slotID uint) ([]SlotOccupancyInfo, error) {
	if s.manager == nil {
		return nil, ErrPKCS11ServiceNotInitialized
	}

	conn, err := s.manager.GetConnection(moduleID, slotID)
	if err != nil {
		return nil, err
	}

	if conn.Backend == nil {
		return nil, nil
	}

	smp, ok := conn.Backend.(slotModelProvider)
	if !ok {
		return nil, nil
	}

	sm := smp.SlotModel()
	if sm == nil {
		return nil, nil
	}

	// Refresh to get latest state from token.
	if refreshErr := sm.Refresh(); refreshErr != nil {
		s.log.Warn("slot model refresh failed", "error", refreshErr)
	}

	allSlots := sm.AllSlots()
	result := make([]SlotOccupancyInfo, 0, len(allSlots))
	for _, slot := range allSlots {
		info, infoErr := sm.SlotOccupancy(slot)
		if infoErr != nil {
			continue
		}
		result = append(result, SlotOccupancyInfo{
			Slot:         string(info.Slot),
			Name:         info.Name,
			Description:  info.Description,
			Occupied:     info.Occupied,
			KeyAlgorithm: info.KeyAlgorithm,
			HasCert:      info.HasCert,
		})
	}
	return result, nil
}

// YubiKeyDetectionResult describes the outcome of a YubiKey library probe.
type YubiKeyDetectionResult struct {
	Found       bool   `json:"found"`
	LibraryPath string `json:"library_path,omitempty"`
	Error       string `json:"error,omitempty"`
}

// yubiKeyLibraryPaths lists common installation paths for the Yubico
// PKCS#11 module across Linux architectures and package managers.
var yubiKeyLibraryPaths = []string{
	"/usr/lib/x86_64-linux-gnu/libykcs11.so",
	"/usr/lib/aarch64-linux-gnu/libykcs11.so",
	"/usr/lib/libykcs11.so",
	"/usr/local/lib/libykcs11.so",
	"/opt/yubico/lib/libykcs11.so",
}

// DetectYubiKey probes the filesystem for the Yubico PKCS#11 module
// (libykcs11.so) and returns the first path found.
func (s *PKCS11Service) DetectYubiKey() YubiKeyDetectionResult {
	for _, p := range yubiKeyLibraryPaths {
		if _, err := os.Stat(p); err == nil {
			s.log.Info("YubiKey PKCS#11 module detected", "path", p)
			return YubiKeyDetectionResult{
				Found:       true,
				LibraryPath: p,
			}
		}
	}
	s.log.Debug("YubiKey PKCS#11 module not found on any known path")
	return YubiKeyDetectionResult{
		Found: false,
		Error: "libykcs11.so not found in any known location",
	}
}

// HasSlotModel reports whether the connected token uses predefined PIV slots.
func (s *PKCS11Service) HasSlotModel(moduleID string, slotID uint) bool {
	if s.manager == nil {
		return false
	}
	conn, err := s.manager.GetConnection(moduleID, slotID)
	if err != nil || conn.Backend == nil {
		return false
	}
	smp, ok := conn.Backend.(slotModelProvider)
	return ok && smp.SlotModel() != nil
}
