// ProbeResult describes a detected PKCS#11 module for the frontend.
type ProbeResult struct {
	LibraryPath string `json:"library_path"`
	DisplayName string `json:"display_name"`
}

// PKCS11Service exposes PKCS#11 token management operations to the frontend.
// It wraps pkg/pkcs11/manager.Manager and is bound to the Wails runtime so
// every exported method is callable from the Svelte frontend.
// PKCS11ConnectHook is called after a PKCS11 token is successfully connected.
// It receives the module ID, library path, slot ID, user PIN, SO PIN (management key),
// and token label.
type PKCS11ConnectHook func(moduleID, libraryPath string, slotID uint, userPIN, soPin, tokenLabel string)

// PKCS11DisconnectHook is called after a PKCS#11 token is disconnected.
// It receives the module ID and slot ID so callers can clean up resources.
type PKCS11DisconnectHook func(moduleID string, slotID uint)

type PKCS11Service struct {
	ctx            context.Context
	log            *slog.Logger
	manager        manager.Manager
	registry       backendregistry.Registry
	connectHook    PKCS11ConnectHook
	disconnectHook PKCS11DisconnectHook

	// testedModules tracks modules that passed TestConnection and are still
	// registered, so a subsequent RegisterModule call can reuse them instead
	// of paying the C_Initialize cost again (YubiKey libykcs11 takes several
	// seconds to enumerate USB on each load).
	testedModules   map[string]string // libraryPath -> moduleID
	testedModulesMu sync.RWMutex
}

// NewPKCS11Service creates a new PKCS11Service with a fresh manager.
func NewPKCS11Service() *PKCS11Service {
	m := manager.New()
	slog.Info("pkcs11_service: created", "manager_available", m.IsAvailable())
	return &PKCS11Service{
		log:           slog.Default().With("component", "pkcs11_service"),
		manager:       m,
		testedModules: make(map[string]string),
	}
}

// SetContext is called by the Wails startup lifecycle hook.
func (s *PKCS11Service) SetContext(ctx context.Context) {
	s.ctx = ctx
}

// SetConnectHook registers a callback that fires after a PKCS#11 token
// is successfully connected. This allows registering the connected token
// as an xkms backend for PIV key generation and other operations.
func (s *PKCS11Service) SetConnectHook(fn PKCS11ConnectHook) {
	s.connectHook = fn
}

// SetDisconnectHook registers a callback that fires after a PKCS#11 token
// is disconnected. This allows unregistering resources (e.g., FIDO2 key backends).
func (s *PKCS11Service) SetDisconnectHook(fn PKCS11DisconnectHook) {
	s.disconnectHook = fn
}

// SetManager sets the underlying PKCS#11 manager.
// This allows injecting a manager with custom configuration or for testing.
func (s *PKCS11Service) SetManager(m manager.Manager) {
	s.manager = m
}

// GetManager returns the underlying PKCS#11 manager.
func (s *PKCS11Service) GetManager() manager.Manager {
	return s.manager
}

// SetRegistry sets the backend registry for state synchronization.
// When set, Connect/Disconnect update the registry state so the frontend
// reflects the actual PKCS#11 session status.
func (s *PKCS11Service) SetRegistry(r backendregistry.Registry) {
	s.registry = r
}

// IsAvailable returns true if PKCS#11 support is compiled in.
func (s *PKCS11Service) IsAvailable() bool {
	if s.manager == nil {
		return false
	}
	return s.manager.IsAvailable()
}

// Close shuts down the PKCS#11 manager and releases all resources.
func (s *PKCS11Service) Close() error {
	if s.manager == nil {
		return nil
	}
	return s.manager.Close()
}

// ProbeModules detects available PKCS#11 modules on the system.
// Returns a list of library paths and suggested display names.
func (s *PKCS11Service) ProbeModules() []ProbeResult {
	probed := manager.ProbeModulesWithNames()
	results := make([]ProbeResult, len(probed))
	for i, p := range probed {
		results[i] = ProbeResult{
			LibraryPath: p.LibraryPath,
			DisplayName: p.DisplayName,
		}
	}
	return results
}

// isSoftHSM2Module checks if the library path is a SoftHSM2 module.
func isSoftHSM2Module(libraryPath string) bool {
	base := strings.ToLower(filepath.Base(libraryPath))
	return strings.Contains(base, "softhsm")
}

// ensureSoftHSM2Config ensures the SoftHSM2 configuration exists.
// If the SOFTHSM2_CONF environment variable is not set and no config exists,
// it creates a default configuration in ~/.config/softhsm2/.
func (s *PKCS11Service) ensureSoftHSM2Config() error {
	// Check if already configured via environment
	if os.Getenv("SOFTHSM2_CONF") != "" {
		s.log.Debug("SoftHSM2 config from environment", "path", os.Getenv("SOFTHSM2_CONF"))
		return nil
	}

	// Check common system paths
	systemPaths := []string{
		"/etc/softhsm2.conf",
		"/etc/softhsm/softhsm2.conf",
	}
	for _, p := range systemPaths {
		if _, err := os.Stat(p); err == nil {
			s.log.Debug("SoftHSM2 system config found", "path", p)
			return nil
		}
	}

	// Create user config directory
	homeDir, err := os.UserHomeDir()
	if err != nil {
		return fmt.Errorf("failed to get home directory: %w", err)
	}

	configDir := filepath.Join(homeDir, ".config", "softhsm2")
	tokenDir := filepath.Join(configDir, "tokens")
	configPath := filepath.Join(configDir, "softhsm2.conf")

	// Check if user config already exists
	if _, err := os.Stat(configPath); err == nil {
		// Config exists, just set the environment variable
		if err := os.Setenv("SOFTHSM2_CONF", configPath); err != nil {
			return fmt.Errorf("failed to set SOFTHSM2_CONF: %w", err)
		}
		s.log.Info("SoftHSM2 user config found", "path", configPath)
		return nil
	}

	// Create directories
	if err := os.MkdirAll(tokenDir, 0700); err != nil {
		return fmt.Errorf("failed to create SoftHSM2 token directory: %w", err)
	}

	// Write config file
	configContent := fmt.Sprintf(softhsm2ConfigTemplate, tokenDir)
	if err := os.WriteFile(configPath, []byte(configContent), 0600); err != nil {
		return fmt.Errorf("failed to write SoftHSM2 config: %w", err)
	}

	// Set environment variable for current process
	if err := os.Setenv("SOFTHSM2_CONF", configPath); err != nil {
		return fmt.Errorf("failed to set SOFTHSM2_CONF: %w", err)
	}

	s.log.Info("SoftHSM2 config auto-created", "config", configPath, "tokens", tokenDir)
	return nil
}

// RegisterModule registers a PKCS#11 library with the manager.
// Returns the module ID that can be used for subsequent operations.
// For SoftHSM2 modules, automatically creates configuration if needed.
func (s *PKCS11Service) RegisterModule(libraryPath, displayName string) (string, error) {
	if s.manager == nil {
		return "", ErrPKCS11ServiceNotInitialized
	}
	if libraryPath == "" {
		return "", ErrPKCS11ModuleRequired
	}

	// Reuse a pre-tested module registration if TestConnection already loaded
	// this library. This avoids a second C_Initialize which can take several
	// seconds on YubiKey (libykcs11 enumerates USB/CCID on every load).
	if s.testedModules != nil {
		s.testedModulesMu.RLock()
		existingID, ok := s.testedModules[libraryPath]
		s.testedModulesMu.RUnlock()
		if ok {
			if _, err := s.manager.GetModule(existingID); err == nil {
				s.log.Info("PKCS#11 module reused from TestConnection",
					"module_id", existingID, "library", libraryPath)
				if persistErr := s.persistModule(existingID, libraryPath, displayName); persistErr != nil {
					s.log.Error("PKCS#11 module reused but config persistence failed",
						"module_id", existingID, "error", persistErr)
				}
				// Clear the cache entry — it has now been "promoted" to a real registration.
				s.testedModulesMu.Lock()
				delete(s.testedModules, libraryPath)
				s.testedModulesMu.Unlock()
				return existingID, nil
			}
			// Stale cache entry — module no longer registered. Drop it and re-register.
			s.testedModulesMu.Lock()
			delete(s.testedModules, libraryPath)
			s.testedModulesMu.Unlock()
		}
	}

	// Auto-configure SoftHSM2 if needed
	if isSoftHSM2Module(libraryPath) {
		if err := s.ensureSoftHSM2Config(); err != nil {
			s.log.Error("failed to configure SoftHSM2", "error", err)
			return "", fmt.Errorf("SoftHSM2 configuration failed: %w", err)
		}
	}

	moduleID, err := s.manager.RegisterModule(libraryPath, displayName)
	if err != nil {
		s.log.Error("failed to register PKCS#11 module",
			"library", libraryPath,
			"error", err)
		return "", err
	}

	// Log the registered module info
	mod, modErr := s.manager.GetModule(moduleID)
	if modErr == nil {
		s.log.Info("PKCS#11 module registered",
			"module_id", moduleID,
			"library", libraryPath,
			"slots", len(mod.Slots))
	}

	// Persist the PKCS#11 backend to the unified config so it survives restarts.
	if persistErr := s.persistModule(moduleID, libraryPath, displayName); persistErr != nil {
		s.log.Error("PKCS#11 module registered in-memory but config persistence failed",
			"module_id", moduleID, "error", persistErr)
		// Don't fail the registration — the module is usable this session.
	}

	return moduleID, nil
}

// persistModule saves a PKCS#11 module entry to the unified config file.
func (s *PKCS11Service) persistModule(moduleID, libraryPath, displayName string) error {
	ucfg, err := config.Load()
	if err != nil {
		return fmt.Errorf("%w: %v", ErrPKCS11ConfigPersistFailed, err)
	}

	entry := config.LocalBackendConfig{
		ID:       moduleID,
		Category: "pkcs11",
		Name:     displayName,
		PKCS11: &config.PKCS11BackendConfig{
			LibraryPath: libraryPath,
		},
	}

	// Replace existing entry with same ID, or append.
	replaced := false
	for i, existing := range ucfg.Backends.Local {
		if existing.ID == moduleID {
			ucfg.Backends.Local[i] = entry
			replaced = true
			break
		}
	}
	if !replaced {
		ucfg.Backends.Local = append(ucfg.Backends.Local, entry)
	}

	if saveErr := config.Save(ucfg); saveErr != nil {
		return fmt.Errorf("%w: %v", ErrPKCS11ConfigPersistFailed, saveErr)
	}

	s.log.Info("PKCS#11 module persisted to config", "module_id", moduleID)
	return nil
}

// RegisterModuleFromConfig registers a PKCS#11 module from persisted config.
// Unlike RegisterModule, this does NOT re-persist to config (avoiding circular
// writes during startup restoration). The moduleID is used as-is rather than
// being generated by the manager.
func (s *PKCS11Service) RegisterModuleFromConfig(moduleID, libraryPath, displayName string) (string, error) {
	if s.manager == nil {
		return "", ErrPKCS11ServiceNotInitialized
	}
	if libraryPath == "" {
		return "", ErrPKCS11ModuleRequired
	}

	// Auto-configure SoftHSM2 if needed
	if isSoftHSM2Module(libraryPath) {
		if err := s.ensureSoftHSM2Config(); err != nil {
			s.log.Error("failed to configure SoftHSM2", "error", err)
			return "", fmt.Errorf("SoftHSM2 configuration failed: %w", err)
		}
	}

	id, err := s.manager.RegisterModule(libraryPath, displayName)
	if err != nil {
		s.log.Error("failed to restore PKCS#11 module from config",
			"module_id", moduleID, "library", libraryPath, "error", err)
		return "", err
	}

	s.log.Info("PKCS#11 module restored from config",
		"module_id", id, "library", libraryPath)
	return id, nil
}

